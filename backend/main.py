def get_all_urls(base_url: str) -> List[str]:
    """
    Discover all accessible URLs from the GitHub Pages site

    Args:
        base_url: The base URL of the GitHub Pages site

    Returns:
        List of all discovered URLs
    """
    logger.info(f"Starting to crawl URLs from: {base_url}")

    # Check robots.txt
    robots_url = urljoin(base_url, "/robots.txt")
    try:
        rp = RobotFileParser()
        rp.set_url(robots_url)
        rp.read()
    except:
        logger.warning("Could not read robots.txt, proceeding anyway")

    all_urls = set()
    to_visit = [base_url]
    visited = set()

    # Common file extensions to avoid
    skip_extensions = {'.pdf', '.jpg', '.jpeg', '.png', '.gif', '.css', '.js', '.ico', '.svg'}

    while to_visit:
        current_url = to_visit.pop(0)

        if current_url in visited:
            continue

        visited.add(current_url)

        try:
            # Check if allowed by robots.txt
            if 'rp' in locals():
                if not rp.can_fetch("*", current_url):
                    logger.info(f"Robots.txt disallows: {current_url}")
                    continue

            response = requests.get(current_url, timeout=10)
            response.raise_for_status()

            # Check if content type is HTML
            content_type = response.headers.get('content-type', '').lower()
            if 'text/html' not in content_type:
                continue

            soup = BeautifulSoup(response.text, 'html.parser')
            all_urls.add(current_url)

            # Find all links on the page
            for link in soup.find_all('a', href=True):
                href = link['href']

                # Convert relative URLs to absolute
                absolute_url = urljoin(current_url, href)

                # Only process URLs from the same domain
                if urlparse(absolute_url).netloc == urlparse(base_url).netloc:
                    # Skip if it has an extension we want to avoid
                    if any(absolute_url.lower().endswith(ext) for ext in skip_extensions):
                        continue

                    # Skip if it's an anchor link
                    if absolute_url.startswith('#'):
                        continue

                    # Add to visit list if not already visited
                    if absolute_url not in visited and absolute_url not in to_visit:
                        to_visit.append(absolute_url)

        except requests.RequestException as e:
            logger.error(f"Error crawling {current_url}: {e}")
            continue
        except Exception as e:
            logger.error(f"Unexpected error crawling {current_url}: {e}")
            continue

    logger.info(f"Discovered {len(all_urls)} URLs")
    return list(all_urls)

def extract_text_from_url(url: str) -> str:
    """
    Extract clean text content from a single page

    Args:
        url: URL to extract text from

    Returns:
        Clean text content from the page
    """
    try:
        response = requests.get(url, timeout=10)
        response.raise_for_status()

        soup = BeautifulSoup(response.text, 'html.parser')

        # Remove script and style elements
        for script in soup(["script", "style", "nav", "header", "footer", "aside"]):
            script.decompose()

        # Get text content
        text = soup.get_text()

        # Clean up text: remove extra whitespace
        lines = (line.strip() for line in text.splitlines())
        chunks = (phrase.strip() for line in lines for phrase in line.split("  "))
        text = ' '.join(chunk for chunk in chunks if chunk)

        logger.info(f"Extracted {len(text)} characters from {url}")
        return text

    except Exception as e:
        logger.error(f"Error extracting text from {url}: {e}")
        return ""

def chunk_text(text: str, chunk_size: int = 512, overlap: int = 128) -> List[str]:
    """
    Split content into semantically meaningful chunks

    Args:
        text: Text to chunk
        chunk_size: Size of each chunk in characters
        overlap: Overlap between chunks in characters

    Returns:
        List of text chunks
    """
    if len(text) <= chunk_size:
        return [text]

    chunks = []
    start = 0

    while start < len(text):
        end = start + chunk_size

        # If we're near the end, include the rest
        if end > len(text):
            end = len(text)

        chunk = text[start:end]
        chunks.append(chunk)

        # Move start by chunk_size - overlap to create overlap
        start = end - overlap

        # Handle case where remaining text is smaller than overlap
        if start >= len(text):
            break

        # Memory optimization: Clear large intermediate variables periodically
        if len(chunks) % 100 == 0:
            import gc
            gc.collect()

    logger.info(f"Text chunked into {len(chunks)} chunks")
    return chunks

def embed(text_chunk: str) -> List[float]:
    """
    Generate embeddings using Cohere API

    Args:
        text_chunk: Text to generate embeddings for

    Returns:
        Embedding vector as a list of floats
    """
    try:
        response = co.embed(
            texts=[text_chunk],
            model="multilingual-22-12-embed",  # Using Cohere's multilingual embedding model
            input_type="search_document"
        )

        embedding = response.embeddings[0]
        logger.debug(f"Generated embedding with {len(embedding)} dimensions")
        return embedding

    except Exception as e:
        logger.error(f"Error generating embedding for chunk: {e}")
        raise

def create_collection(collection_name: str = "rag_embedding"):
    """
    Initialize Qdrant collection named 'rag_embedding'

    Args:
        collection_name: Name of the collection to create
    """
    try:
        # Check if collection already exists
        collections = qdrant_client.get_collections()
        collection_names = [col.name for col in collections.collections]

        if collection_name in collection_names:
            logger.info(f"Collection '{collection_name}' already exists, using existing collection")
            return

        # Create new collection with 768-dim vectors (for Cohere embeddings)
        qdrant_client.create_collection(
            collection_name=collection_name,
            vectors_config=models.VectorParams(size=768, distance=models.Distance.COSINE),
        )

        logger.info(f"Created collection '{collection_name}' with 768-dim vectors")

    except Exception as e:
        logger.error(f"Error creating collection '{collection_name}': {e}")
        raise

def save_chunk_to_qdrant(content_chunk: ContentChunk, embedding: VectorEmbedding, collection_name: str = "rag_embedding"):
    """
    Store vectors with metadata in Qdrant

    Args:
        content_chunk: ContentChunk object containing the text and metadata
        embedding: VectorEmbedding object containing the vector
        collection_name: Name of the collection to store in
    """
    try:
        # Prepare the point to be inserted
        point = models.PointStruct(
            id=content_chunk.id,
            vector=embedding.vector,
            payload={
                "text": content_chunk.text,
                "url": content_chunk.url,
                "section": content_chunk.section,
                "chunk_index": content_chunk.chunk_index,
                "source": content_chunk.source
            }
        )

        # Upsert the point to the collection
        qdrant_client.upsert(
            collection_name=collection_name,
            points=[point]
        )

        logger.info(f"Saved chunk to Qdrant with ID: {content_chunk.id}")

    except Exception as e:
        logger.error(f"Error saving chunk to Qdrant: {e}")
        raise

def search_similar_content(query_text: str, top_k: int = 5, collection_name: str = "rag_embedding") -> List[Dict]:
    """
    Implement similarity search functionality for content retrieval

    Args:
        query_text: The text to search for similar content
        top_k: Number of top results to return
        collection_name: Name of the collection to search in

    Returns:
        List of dictionaries containing the most similar content chunks with their metadata
    """
    try:
        # Generate embedding for the query text
        query_embedding = embed(query_text)

        # Perform the search in Qdrant
        search_results = qdrant_client.search(
            collection_name=collection_name,
            query_vector=query_embedding,
            limit=top_k,
            with_payload=True
        )

        # Format the results
        results = []
        for result in search_results:
            results.append({
                "id": result.id,
                "text": result.payload.get("text", ""),
                "url": result.payload.get("url", ""),
                "section": result.payload.get("section", ""),
                "chunk_index": result.payload.get("chunk_index", 0),
                "score": result.score,
                "source": result.payload.get("source", "web_content")
            })

        logger.info(f"Found {len(results)} similar content chunks for query")
        return results

    except Exception as e:
        logger.error(f"Error performing similarity search: {e}")
        raise


def validate_query_performance(query_text: str, expected_time: float = 2.0, collection_name: str = "rag_embedding") -> bool:
    """
    Add query performance validation (under 2 seconds for 90% of queries)

    Args:
        query_text: The text to search for performance validation
        expected_time: Expected maximum time in seconds
        collection_name: Name of the collection to search in

    Returns:
        Boolean indicating if query performed within expected time
    """
    import time

    start_time = time.time()
    try:
        search_similar_content(query_text, top_k=5, collection_name=collection_name)
        end_time = time.time()

        query_time = end_time - start_time
        logger.info(f"Query executed in {query_time:.2f} seconds (limit: {expected_time}s)")

        return query_time <= expected_time
    except Exception as e:
        logger.error(f"Error validating query performance: {e}")
        return False


def check_content_exists(url: str, chunk_index: int, collection_name: str = "rag_embedding") -> bool:
    """
    Check if content already exists in Qdrant to avoid duplicates
    """
    try:
        import hashlib
        chunk_id = hashlib.md5(f"{url}_{chunk_index}_".encode()).hexdigest()

        # Try to retrieve the point by ID
        records = qdrant_client.retrieve(
            collection_name=collection_name,
            ids=[chunk_id],
            with_payload=True,
            with_vectors=False
        )

        return len(records) > 0
    except Exception:
        # If there's an error (e.g., collection doesn't exist), assume content doesn't exist
        return False


def get_content_hash(text: str, url: str, chunk_index: int) -> str:
    """
    Generate a consistent hash for content to ensure reproducibility across runs
    """
    import hashlib
    content_to_hash = f"{text}_{url}_{chunk_index}".encode('utf-8')
    return hashlib.sha256(content_to_hash).hexdigest()


