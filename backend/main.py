def main():
    """
    Execute the complete pipeline
    """
    logger.info("Starting web content ingestion pipeline")

    # Target URL
    base_url = "https://maryamhussan.github.io/Physical-AI-And-Humanoid-Robotics"

    try:
        # Step 1: Get all URLs
        urls = get_all_urls(base_url)

        if not urls:
            logger.warning("No URLs found, exiting")
            return

        # Step 2: Create Qdrant collection
        create_collection("rag_embedding")

        # Step 3: Process each URL
        processed_count = 0
        for i, url in enumerate(urls):
            logger.info(f"Processing URL {i+1}/{len(urls)}: {url}")

            # Extract text
            text = extract_text_from_url(url)
            if not text.strip():
                logger.warning(f"No text extracted from {url}, skipping")
                continue

            # Chunk text
            chunks = chunk_text(text)

            # Process each chunk
            for j, chunk_text_content in enumerate(chunks):
                if not chunk_text_content.strip():
                    continue

                # Check if this content already exists to avoid duplicates
                if check_content_exists(url, j, "rag_embedding"):
                    logger.info(f"Content already exists for URL {url} chunk {j}, skipping")
                    continue

                try:
                    # Generate embedding
                    embedding_vector = embed(chunk_text_content)

                    # Create unique ID for this chunk
                    import hashlib
                    chunk_id = hashlib.md5(f"{url}_{j}_{len(chunk_text_content)}".encode()).hexdigest()

                    # Create ContentChunk object
                    content_chunk = ContentChunk(
                        id=chunk_id,
                        text=chunk_text_content,
                        url=url,
                        chunk_index=j,
                        source="web_content"
                    )

                    # Create VectorEmbedding object
                    vector_embedding = VectorEmbedding(
                        id=chunk_id,
                        vector=embedding_vector,
                        content_chunk_id=chunk_id
                    )

                    # Save to Qdrant
                    save_chunk_to_qdrant(content_chunk, vector_embedding, "rag_embedding")

                    processed_count += 1

                    # Add a small delay to respect API limits
                    time.sleep(0.1)

                    # Memory optimization: Clean up large variables and run garbage collection periodically
                    if j % 50 == 0:  # Every 50 chunks
                        del embedding_vector, content_chunk, vector_embedding  # Explicitly delete large objects
                        import gc
                        gc.collect()

                except Exception as e:
                    logger.error(f"Error processing chunk {j} from {url}: {e}")
                    continue

        logger.info(f"Pipeline completed successfully. Processed {processed_count} new content chunks.")

        # Demonstrate search functionality
        logger.info("Testing search functionality with sample query...")
        sample_query = "What is Physical AI and Humanoid Robotics?"
        search_results = search_similar_content(sample_query)

        if search_results:
            logger.info(f"Found {len(search_results)} relevant results:")
            for i, result in enumerate(search_results[:3]):  # Show first 3 results
                logger.info(f"Result {i+1}: Score {result['score']:.3f} from {result['url']}")
                logger.info(f"  Text preview: {result['text'][:100]}...")
        else:
            logger.info("No results found for the sample query")

        # Demonstrate retrieval functionality for RAG
        logger.info("Demonstrating RAG retrieval functionality...")
        demonstrate_retrieval_functionality()

        # Demonstrate agent functionality
        logger.info("Demonstrating RAG agent functionality...")
        demonstrate_agent_functionality()

    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        raise


if __name__ == "__main__":
    main()
