# Data Model Classes
@dataclass
class ContentChunk:
    """
    Represents a segment of extracted text from the book
    """
    id: str
    text: str
    url: str
    section: str = ""
    chunk_index: int = 0
    source: str = "web_content"

@dataclass
class VectorEmbedding:
    """
    Numeric representation of content semantics generated by the Cohere model
    """
    id: str
    vector: List[float]
    content_chunk_id: str

@dataclass
class ConfigurationParameters:
    """
    Settings that control the ingestion process
    """
    source_url: str
    chunk_size: int = 512
    chunk_overlap: int = 128
    cohere_model: str = "multilingual-22-12-embed"
    qdrant_collection: str = "rag_embedding"

    def validate(self) -> List[str]:
        """
        Validate configuration parameters and return list of validation errors
        """
        errors = []

        # Validate source URL format
        if not self.source_url or not self.source_url.startswith(('http://', 'https://')):
            errors.append("source_url must be a valid HTTP/HTTPS URL")

        # Validate chunk_size is positive
        if self.chunk_size <= 0:
            errors.append("chunk_size must be a positive integer")

        # Validate chunk_overlap is non-negative and smaller than chunk_size
        if self.chunk_overlap < 0:
            errors.append("chunk_overlap must be non-negative")
        if self.chunk_overlap >= self.chunk_size:
            errors.append("chunk_overlap must be smaller than chunk_size")

        # Validate cohere_model is not empty
        if not self.cohere_model.strip():
            errors.append("cohere_model cannot be empty")

        # Validate qdrant_collection is not empty
        if not self.qdrant_collection.strip():
            errors.append("qdrant_collection cannot be empty")

        return errors

    @classmethod
    def from_env(cls) -> 'ConfigurationParameters':
        """
        Create ConfigurationParameters from environment variables
        """
        source_url = os.getenv("SOURCE_URL", "https://maryamhussan.github.io/Physical-AI-And-Humanoid-Robotics")
        chunk_size = int(os.getenv("CHUNK_SIZE", "512"))
        chunk_overlap = int(os.getenv("CHUNK_OVERLAP", "128"))
        cohere_model = os.getenv("COHERE_MODEL", "multilingual-22-12-embed")
        qdrant_collection = os.getenv("QDRANT_COLLECTION", "rag_embedding")

        return cls(
            source_url=source_url,
            chunk_size=chunk_size,
            chunk_overlap=chunk_overlap,
            cohere_model=cohere_model,
            qdrant_collection=qdrant_collection
        )

    def to_dict(self) -> Dict[str, any]:
        """
        Convert configuration to dictionary
        """
        return {
            'source_url': self.source_url,
            'chunk_size': self.chunk_size,
            'chunk_overlap': self.chunk_overlap,
            'cohere_model': self.cohere_model,
            'qdrant_collection': self.qdrant_collection
        }

